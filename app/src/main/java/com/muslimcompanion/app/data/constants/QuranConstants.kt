        var lastWasConsonant = false
        val s = clean

        while (i < s.length) {
            val ch = s[i]
            if (ch == '\'' || ch == '’' || ch == '`' || ch == '-') {
                i++
                lastWasConsonant = false
                continue
            }

            var matchedConsonant: String? = null
            var cLen = 0
            for ((key, value) in CONSONANTS) {
                if (s.startsWith(key, i)) {
                    matchedConsonant = value
                    cLen = key.length
                    break
                }
            }

            if (matchedConsonant != null) {
                res.append(matchedConsonant)
                i += cLen
                lastWasConsonant = true

                for ((vKey, vVal) in VOWELS) {
                    if (s.startsWith(vKey, i)) {
                        res.append(if (vKey == "a") "া" else vVal)
                        i += vKey.length
                        lastWasConsonant = false
                        break
                    }
                }
                continue
            }

            var matchedVowelKey: String? = null
            var matchedVowelVal: String? = null
            for ((vKey, vVal) in VOWELS) {
                if (s.startsWith(vKey, i)) {
                    matchedVowelKey = vKey
                    matchedVowelVal = vVal
                    break
                }
            }

            if (matchedVowelKey != null) {
                if (lastWasConsonant) {
                    res.append(if (matchedVowelKey == "a") "া" else matchedVowelVal)
                } else {
                    res.append(INIT_VOWELS[matchedVowelKey] ?: matchedVowelVal)
                }
                i += matchedVowelKey.length
                lastWasConsonant = false
                continue
            }

            FALLBACK_MAP[ch]?.let { res.append(it) }
            i++
            lastWasConsonant = false
        }

        return res.toString()
            .replace(Regex("া+"), "া")
            .replace(Regex("ি+"), "ি")
            .replace(Regex("ী+"), "ী")
            .replace(Regex("ু+"), "ু")
            .replace(Regex("ূ+"), "ূ")
    }

    fun transliterateLatinToBengali(text: String): String {
        if (text.isBlank()) return ""
        val normalized = text.replace(';', ',').replace(':', ' ')
        val words = normalized.trim().split(Regex("\\s+"))
        val converted = words.mapNotNull { word ->
            if (word.isBlank()) return@mapNotNull null
            val hasComma = word.endsWith(",")
            val core = if (hasComma) word.dropLast(1) else word
            val res = if (core.contains("-")) {
                core.split("-").map { convertSingleWord(it) }.joinToString("-")
            } else {
                convertSingleWord(core)
            }
            if (res.isNotBlank()) (if (hasComma) "$res," else res) else null
        }
        val combined = converted.joinToString(" ").trim()
        return if (combined.isNotBlank() && !combined.endsWith("।") && !combined.endsWith("!") && !combined.endsWith("?")) {
            "$combined।"
        } else {
            combined
        }
    }

    fun getPronunciation(surahNum: Int, ayahNum: Int, fallbackEnglishTranslit: String): String {
        val specific = FAMOUS_PRONUNCIATIONS[surahNum]?.get(ayahNum)
        if (specific != null) return specific
        if (fallbackEnglishTranslit.isNotBlank()) {
            return transliterateLatinToBengali(fallbackEnglishTranslit)
        }
        return "তিলাওয়াত শুনুন ও আরবি পাঠ অনুসরণ করুন।"
    }
